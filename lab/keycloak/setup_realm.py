#!/usr/bin/env python3
"""Create the delegation lab realm in a local Keycloak (26.x).

Builds realm `lab` as described in lab/README.md:
  - user `alice` (synthetic) with roles files-read and files-write, not admin
  - clients agent-app, sub-agent, mcp-server, canary-api (each one an audience)
  - scopes files:read, files:write, admin (each tied to a role, so a user
    without the role can't get the scope)
  - standard token exchange (RFC 8693) switched on for the three clients that
    act on alice's behalf
  - delegation (preview): sub-agent and mcp-server may act for users, so a
    token exchange with an actor_token yields an `act` claim. agent-app needs
    consent, as Keycloak requires for delegation, so alice signs in with the
    browser (code) flow; kc.py scripts that flow for the lab user.

Start Keycloak with:
    --features=token-exchange-delegation,parameterized-scopes,admin-fine-grained-authz:v2

Client secrets and alice's password are generated by Keycloak or this script
and written to lab/keycloak/secrets/lab-clients.json (git-ignored). Nothing
secret is printed. Alice's user id and the client ids go to
lab/bench/lab-config.json, which the scoring bench reads.

Usage:
    export KC_ADMIN_PASSWORD=...      # the local bootstrap admin password
    python3 lab/keycloak/setup_realm.py [--reset]

Standard library only.
"""

import argparse
import getpass
import json
import os
import secrets as pysecrets
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kc import KC_URL, REALM, REDIRECT, SECRETS_FILE, KeycloakError, http  # noqa: E402

BENCH_CONFIG = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "..", "bench", "lab-config.json")

ROLES = ["files-read", "files-write", "admin"]
SCOPE_ROLE = {"files:read": "files-read", "files:write": "files-write",
              "admin": "admin"}
AUDIENCES = ["sub-agent", "mcp-server", "canary-api"]

# Clients allowed to act for users (delegation permission in Keycloak).
ACTORS = ["sub-agent", "mcp-server"]

# Which audience scopes each client puts in the tokens it gets by default.
# A client can only exchange a token whose aud names it, so the chain is:
# alice@agent-app (aud sub-agent, mcp-server) -> sub-agent exchanges for
# mcp-server -> mcp-server exchanges for canary-api.
CLIENTS = {
    "agent-app": {"default_aud": ["sub-agent", "mcp-server"],
                  "direct_grants": False, "service_account": True,
                  "exchange": True},
    "sub-agent": {"default_aud": ["mcp-server"], "direct_grants": False,
                  "service_account": True, "exchange": True},
    "mcp-server": {"default_aud": ["canary-api"], "direct_grants": False,
                   "service_account": True, "exchange": True},
    "canary-api": {"default_aud": [], "direct_grants": False,
                   "service_account": False, "exchange": False},
}


def admin_token(user, password):
    data = {"grant_type": "password", "client_id": "admin-cli",
            "username": user, "password": password}
    return http("POST", f"{KC_URL}/realms/master/protocol/openid-connect/token",
                data, form=True)["access_token"]


def setup_delegation(r, tok, client_uuids):
    """Turn on Keycloak's delegation preview for the lab. Returns True if done."""
    scopes = {cs["name"]: cs["id"] for cs in http("GET", f"{r}/client-scopes", token=tok)}
    if "delegation:client" not in scopes:
        print("delegation skipped: start Keycloak with --features="
              "token-exchange-delegation,parameterized-scopes,admin-fine-grained-authz:v2")
        return False
    http("PUT", f"{r}/clients/{client_uuids['agent-app']}/optional-client-scopes/"
         f"{scopes['delegation:client']}", {}, token=tok)
    realm = http("GET", r, token=tok)
    realm["adminPermissionsEnabled"] = True
    http("PUT", r, realm, token=tok)
    perms = next(c for c in http("GET", f"{r}/clients?clientId=admin-permissions", token=tok))
    authz = f"{r}/clients/{perms['id']}/authz/resource-server"
    policy = http("POST", f"{authz}/policy/client", {
        "name": "lab actors", "logic": "POSITIVE",
        "clients": [client_uuids[c] for c in ACTORS]}, token=tok)
    http("POST", f"{authz}/permission/scope", {
        "name": "lab actors may act for all users", "resourceType": "Users",
        "scopes": ["delegate"], "policies": [policy["id"]],
        "decisionStrategy": "UNANIMOUS"}, token=tok)
    print("delegation on: " + ", ".join(ACTORS) + " may act for users "
          "(agent-app requests scope delegation:client:<actor>, with consent)")
    return True


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--reset", action="store_true",
                   help="delete realm `lab` first if it exists")
    p.add_argument("--access-token-minutes", type=int, default=5,
                   help="access token lifetime (Keycloak default is 5)")
    a = p.parse_args()

    user = os.environ.get("KC_ADMIN_USER", "admin")
    password = os.environ.get("KC_ADMIN_PASSWORD") or getpass.getpass(
        f"Keycloak admin password for '{user}': ")
    tok = admin_token(user, password)
    base = f"{KC_URL}/admin/realms"
    r = f"{base}/{REALM}"

    existing = [x["realm"] for x in http("GET", base, token=tok)]
    if REALM in existing:
        if not a.reset:
            sys.exit(f"Realm '{REALM}' already exists. Re-run with --reset to rebuild it.")
        http("DELETE", r, token=tok)
        print(f"deleted realm {REALM}")

    http("POST", base, {"realm": REALM, "enabled": True,
                        "accessTokenLifespan": a.access_token_minutes * 60}, token=tok)
    print(f"created realm {REALM} (access tokens live {a.access_token_minutes} min)")

    for role in ROLES:
        http("POST", f"{r}/roles", {"name": role}, token=tok)
    roles = {x["name"]: x for x in http("GET", f"{r}/roles", token=tok)}

    scope_ids = {}
    for name, role in SCOPE_ROLE.items():
        http("POST", f"{r}/client-scopes", {
            "name": name, "protocol": "openid-connect",
            "attributes": {"include.in.token.scope": "true",
                           "display.on.consent.screen": "false"}}, token=tok)
    for aud in AUDIENCES:
        http("POST", f"{r}/client-scopes", {
            "name": f"aud-{aud}", "protocol": "openid-connect",
            "attributes": {"include.in.token.scope": "false",
                           "display.on.consent.screen": "false"},
            "protocolMappers": [{
                "name": f"audience {aud}", "protocol": "openid-connect",
                "protocolMapper": "oidc-audience-mapper",
                "config": {"included.client.audience": aud,
                           "access.token.claim": "true",
                           "id.token.claim": "false",
                           "introspection.token.claim": "true"}}]}, token=tok)
    for cs in http("GET", f"{r}/client-scopes", token=tok):
        scope_ids[cs["name"]] = cs["id"]
    for name, role in SCOPE_ROLE.items():
        http("POST", f"{r}/client-scopes/{scope_ids[name]}/scope-mappings/realm",
             [roles[role]], token=tok)
    print("created scopes files:read, files:write, admin and audience scopes")

    client_secrets, client_uuids = {}, {}
    for cid, cfg in CLIENTS.items():
        rep = {"clientId": cid, "enabled": True, "publicClient": False,
               "protocol": "openid-connect",
               "standardFlowEnabled": cid == "agent-app",
               "consentRequired": cid == "agent-app",
               "fullScopeAllowed": False,
               "directAccessGrantsEnabled": cfg["direct_grants"],
               "serviceAccountsEnabled": cfg["service_account"],
               "redirectUris": [REDIRECT, "http://127.0.0.1:*", "http://localhost:*"]
               if cid == "agent-app" else [],
               "attributes": {"standard.token.exchange.enabled":
                              "true" if cfg["exchange"] else "false"}}
        loc = http("POST", f"{r}/clients", rep, token=tok)["_location"]
        uuid = loc.rsplit("/", 1)[-1]
        for aud in cfg["default_aud"]:
            http("PUT", f"{r}/clients/{uuid}/default-client-scopes/{scope_ids['aud-' + aud]}",
                 {}, token=tok)
        if cid != "canary-api":
            for name in SCOPE_ROLE:
                http("PUT", f"{r}/clients/{uuid}/optional-client-scopes/{scope_ids[name]}",
                     {}, token=tok)
        client_secrets[cid] = http("GET", f"{r}/clients/{uuid}/client-secret",
                                   token=tok)["value"]
        client_uuids[cid] = uuid
    print("created clients " + ", ".join(CLIENTS))

    delegation = setup_delegation(r, tok, client_uuids)

    alice_password = pysecrets.token_urlsafe(18)
    loc = http("POST", f"{r}/users", {
        "username": "alice", "enabled": True, "emailVerified": True,
        "firstName": "Alice", "lastName": "Lab", "email": "alice@lab.invalid",
        "credentials": [{"type": "password", "value": alice_password,
                         "temporary": False}]}, token=tok)["_location"]
    alice_id = loc.rsplit("/", 1)[-1]
    http("POST", f"{r}/users/{alice_id}/role-mappings/realm",
         [roles["files-read"], roles["files-write"]], token=tok)
    print("created user alice with files-read and files-write (no admin)")

    os.makedirs(os.path.dirname(SECRETS_FILE), exist_ok=True)
    with open(SECRETS_FILE, "w") as f:
        json.dump({"kc_url": KC_URL, "realm": REALM, "clients": client_secrets,
                   "alice_password": alice_password}, f, indent=2)
    os.chmod(SECRETS_FILE, 0o600)

    config = {"issuer": f"{KC_URL}/realms/{REALM}",
              "jwks_url": f"{KC_URL}/realms/{REALM}/protocol/openid-connect/certs",
              "alice": {"sub": alice_id, "username": "alice"},
              "clients": list(CLIENTS),
              "hops": ["mcp-server", "canary-api"],
              "hop_audience": {"mcp-server": "mcp-server",
                               "canary-api": "canary-api"},
              "granted_scopes": ["files:read", "files:write"],
              "delegation_enabled": delegation}
    with open(BENCH_CONFIG, "w") as f:
        json.dump(config, f, indent=2)
        f.write("\n")

    print(f"secrets written to {os.path.relpath(SECRETS_FILE)} (git-ignored, mode 600)")
    print(f"bench config written to {os.path.relpath(BENCH_CONFIG)}")
    print("next: python3 lab/keycloak/check_exchange.py")


if __name__ == "__main__":
    try:
        main()
    except KeycloakError as exc:
        sys.exit(f"Keycloak refused a request: {exc}")
